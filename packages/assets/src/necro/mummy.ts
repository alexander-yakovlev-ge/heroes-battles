/**
 * Витки бинта поперёк конечности от a до b шириной w: тёмная щель и светлая кромка,
 * чуть наискось. gaps — номера витков, где бинт разошёлся и видна высохшая кожа.
 */
function wraps(p: Pt, q: Pt, w: number, count: number, t: Tone = B, gaps: number[] = []): string {
  const dx = q[0] - p[0]
  const dy = q[1] - p[1]
  const l = Math.hypot(dx, dy) || 1
  const nx = (-dy / l) * w * 0.48
  const ny = (dx / l) * w * 0.48
  const sx = (dx / l) * w * 0.22
  const sy = (dy / l) * w * 0.22
  let s = ''
  for (let i = 1; i < count; i++) {
    const c = lerp(p, q, i / count)
    const d = `M${(c[0] + nx - sx).toFixed(2)},${(c[1] + ny - sy).toFixed(2)} L${(c[0] - nx + sx).toFixed(2)},${(c[1] - ny + sy).toFixed(2)}`
    if (gaps.includes(i)) {
      const e = `M${(c[0] + nx * 0.6).toFixed(2)},${(c[1] + ny * 0.6).toFixed(2)} L${(c[0] - nx * 0.4).toFixed(2)},${(c[1] - ny * 0.4).toFixed(2)}`
      s += line(e, DRY, w * 0.22, 0.9)
    }
    s += line(d, t.lo, 0.55, 0.8) + `<g transform="translate(${(-dx / l) * 0.5} ${(-dy / l) * 0.5})">${line(d, t.hi, 0.35, 0.8)}</g>`
  }
  return s
}

