import { Art, type Tone, C, eye, fill, glow, groundShadow, limbPath, line, smooth, tatters, tint } from './kit.js'

const a = new Art('bansh')

const SKIN = { hi: '#ffffff', base: '#d6e4ee', lo: '#6c7c98', tex: 'skin' } satisfies Tone
const HAIR = { hi: '#d8d4ea', base: '#8f86a8', lo: '#2e2842' }
const EDGE = '#4a4170'

const gown = a.lin('gown', [60, 30], [40, 90], [[0, '#c6d2ea', 0.95], [0.4, '#93a4cc', 0.8], [0.8, '#5a6a9a', 0.3], [1, '#3a3f6a', 0]])
const hairPaint = a.lin('hair', [64, 16], [16, 50], [[0, HAIR.base, 1], [0.55, '#6e6690', 0.85], [1, HAIR.lo, 0]])
const soft = (d: string, paint: string, op = 1) => `<path d="${d}" fill="${paint}"${op < 1 ? ` opacity="${op}"` : ''} stroke="${EDGE}" stroke-width="0.6" stroke-linejoin="round" stroke-opacity="0.6"/>`

/** Длинная прядь, струящаяся назад по ветру */
const strand = (pts: [number, number][], w: number, op: number) => line(smooth(pts), HAIR.lo, w + 0.6, op * 0.6) + line(smooth(pts), HAIR.base, w, op) + line(smooth(pts), HAIR.hi, w * 0.3, op * 0.7)

