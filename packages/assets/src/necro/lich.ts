/** Колдовское пламя: языки зелёного огня вокруг ядра */
const flame = (x: number, y: number, s: number) =>
  glow(a, x, y, 9 * s, C.glow, 0.55) +
  fill(smooth([[x - 3 * s, y + 1 * s], [x - 2.6 * s, y - 3 * s], [x - 1 * s, y - 2 * s], [x, y - 6 * s], [x + 1.4 * s, y - 2.6 * s], [x + 3 * s, y - 4 * s], [x + 3.2 * s, y + 0.6 * s], [x + 0.2 * s, y + 3 * s]], true), a.rad('flame', [x, y], 5 * s, [[0, '#ffffff'], [0.35, C.glowSoft], [0.75, C.glow], [1, C.glowDeep]]), 0) +
  `<circle cx="${x}" cy="${y}" r="${1.4 * s}" fill="#ffffff"/>`

