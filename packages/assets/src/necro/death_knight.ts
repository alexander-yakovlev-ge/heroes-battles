/** Нога коня-скелета: кости по суставам, копыто в железной подкове */
function horseLeg(p: Pt[], t: Tone, w = 2.2): string {
  let s = ''
  for (let i = 0; i < p.length - 1; i++) s += bone(a, p[i]!, p[i + 1]!, w * (1 - i * 0.12), t)
  const [x, y] = p[p.length - 1]!
  return (
    s +
    fill(smooth([[x - 2.4, y - 0.6], [x + 1.8, y - 1], [x + 3, y + 3], [x - 2.6, y + 3.2]], true), a.sph(T.iron), 0.6) +
    line(`M${x - 2.4},${y + 2.6} L${x + 2.8},${y + 2.4}`, T.metal.hi, 0.5, 0.8)
  )
}

